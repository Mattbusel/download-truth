"""Summarize batch JSONL output into docs/results.md and a compact JSON.

Usage: python scripts/summarize.py results/crates.jsonl results/npm.jsonl results/vc_npm.tsv results/vc_crates.tsv
"""
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(paths):
    rs = {}
    for p in paths:
        for line in open(p, encoding="utf-8"):
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            rs[(r["ecosystem"], r["name"])] = r
    return rs


def comp(r, k):
    return next(c for c in r["components"] if c["key"] == k)["share"]


def main():
    jsonl = [a for a in sys.argv[1:] if a.endswith(".jsonl")]
    tsv = [a for a in sys.argv[1:] if a.endswith(".tsv")]
    rs = load(jsonl)
    vc = {}
    for t in tsv:
        eco = "crates" if "crates" in t else "npm"
        for line in open(t, encoding="utf-8"):
            if line.strip():
                name, co = line.rstrip("\n").split("\t")
                vc[(eco, name)] = co
    top_npm = [l.strip() for l in open(ROOT / "results" / "npm_top200.txt") if l.strip()]
    out = ["# Results", "", "Generated by `scripts/summarize.py` from `download-truth batch` runs. Window: the 90 complete UTC days before the run. Every number below is reproducible with `download-truth crate <name>` or `download-truth npm <name>` on the same day.", ""]
    summary = {}
    for label, sel in [
        ("Top 200 crates by 90-day downloads", lambda k: k[0] == "crates" and k not in vc),
        ("Top 200 npm packages (npm-high-impact top-download list)", lambda k: k[0] == "npm" and k[1] in top_npm),
        ("Venture-backed companies' flagship packages", lambda k: k in vc),
    ]:
        g = [r for k, r in rs.items() if sel(k) and r["window_downloads"] > 0]
        if not g:
            continue
        noise = [r["noise_share"] for r in g]
        lock = [comp(r, "lockfile") for r in g]
        flat = [comp(r, "flat") for r in g]
        rel = [comp(r, "release") for r in g]
        pin = [comp(r, "pinned_line") for r in g]
        tot = sum(r["window_downloads"] for r in g)
        real = sum(r["real_downloads"] for r in g)
        mostly = sum(1 for r in g if r["verdict"] == "MOSTLY NOISE")
        s = dict(n=len(g), mostly_noise=mostly, median_noise=st.median(noise), median_lockfile=st.median(lock),
                 median_flat=st.median(flat), median_release=st.median(rel), median_pinned=st.median(pin),
                 downloads=tot, real_downloads=real, real_share_weighted=real / tot if tot else 0)
        summary[label] = s
        out += [f"## {label}", "",
                f"- packages: {len(g)}; MOSTLY NOISE (noise over 50%): **{mostly}**",
                f"- downloads in the window: {tot:,}; the real part: {real:,.0f} (**{real / tot * 100:.1f}%**)",
                f"- median noise share {st.median(noise) * 100:.1f}%; median lockfile replays {st.median(lock) * 100:.1f}%, flat automation {st.median(flat) * 100:.1f}%, release-time {st.median(rel) * 100:.1f}%, pinned old line {st.median(pin) * 100:.1f}%",
                "", "| package | company | window downloads | lockfile | pinned line | release | flat | real | real/weekday | verdict |",
                "|---|---|---:|---:|---:|---:|---:|---:|---:|---|"]
        for r in sorted(g, key=lambda r: -r["noise_share"]):
            co = vc.get((r["ecosystem"], r["name"]), "")
            out.append(f"| {r['name']} | {co} | {r['window_downloads']:,} | {comp(r, 'lockfile') * 100:.1f}% | {comp(r, 'pinned_line') * 100:.1f}% | {comp(r, 'release') * 100:.1f}% | {comp(r, 'flat') * 100:.1f}% | {r['real_share'] * 100:.1f}% | {r['real_users_per_weekday']:,.0f} | {r['verdict']} |")
        out.append("")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "results.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    json.dump(summary, open(ROOT / "docs" / "summary.json", "w", encoding="utf-8"), indent=1)
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
